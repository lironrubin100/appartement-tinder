do $test$
declare
  actor constant uuid := '00000000-0000-4000-8000-000000000001';
  outsider constant uuid := '00000000-0000-4000-8000-000000000002';
  listing constant uuid := '10000000-0000-4000-8000-000000000001';
  d public.listing_drafts; other_d public.listing_drafts; edit_d public.listing_drafts; result public.listing_drafts;
  path text; other_path text; photos jsonb; n integer; caught boolean;
begin
  if (select public from storage.buckets where id='listing-draft-media') is distinct from false then raise exception 'draft bucket is public'; end if;
  perform set_config('request.jwt.claim.sub',actor::text,true); execute 'set local role authenticated';
  d := public.create_listing_draft(); other_d := public.create_listing_draft();
  path := actor::text || '/' || d.id::text || '/50000000-0000-4000-8000-000000000001.jpg';
  other_path := actor::text || '/' || other_d.id::text || '/50000000-0000-4000-8000-000000000002.jpg';
  insert into storage.objects(id,bucket_id,name,owner_id) values('50000000-0000-4000-8000-000000000001','listing-draft-media',path,actor::text);
  insert into storage.objects(id,bucket_id,name,owner_id) values('50000000-0000-4000-8000-000000000002','listing-draft-media',other_path,actor::text);
  if (select count(*) from storage.objects where bucket_id='listing-draft-media' and name=path)<>1 then raise exception 'owner cannot read'; end if;
  caught := false;
  begin insert into storage.objects(id,bucket_id,name,owner_id) values(gen_random_uuid(),'listing-draft-media',actor::text || '/60000000-0000-4000-8000-000000000001/50000000-0000-4000-8000-000000000003.jpg',actor::text);
  exception when insufficient_privilege then caught := true; end;
  if not caught then raise exception 'upload to absent draft'; end if;
  caught := false;
  begin insert into storage.objects(id,bucket_id,name,owner_id) values(gen_random_uuid(),'listing-draft-media',actor::text || '/' || d.id::text || '/../../unsafe.jpg',actor::text);
  exception when insufficient_privilege then caught := true; end;
  if not caught then raise exception 'invalid path accepted'; end if;
  update storage.objects set name=path || '.png' where bucket_id='listing-draft-media' and name=path;
  get diagnostics n = row_count; if n<>0 then raise exception 'immutable object replaced'; end if;
  photos := jsonb_build_array(jsonb_build_object('kind','draft','objectPath',path));
  result := public.set_listing_draft_photos(d.id,0,photos);
  if result.revision<>1 or result.photos<>photos then raise exception 'photo association/order not persisted'; end if;
  caught := false;
  begin perform public.set_listing_draft_photos(d.id,0,'[]');
  exception when others then if sqlerrm<>'DRAFT_CONFLICT' then raise; end if; caught := true; end;
  if not caught then raise exception 'stale photo write allowed'; end if;
  caught := false;
  begin perform public.set_listing_draft_photos(d.id,1,jsonb_build_array(jsonb_build_object('kind','draft','objectPath',other_path)));
  exception when others then if sqlerrm<>'PHOTO_UNAVAILABLE' then raise; end if; caught := true; end;
  if not caught then raise exception 'cross-draft association allowed'; end if;
  caught := false;
  begin perform public.set_listing_draft_photos(d.id,1,photos || photos);
  exception when others then if sqlerrm<>'INVALID_PHOTOS' then raise; end if; caught := true; end;
  if not caught then raise exception 'duplicate object allowed'; end if;
  caught := false;
  begin perform public.set_listing_draft_photos(d.id,1,'[{"kind":"draft","objectPath":"https://example.invalid/image.jpg"}]');
  exception when others then if sqlerrm<>'PHOTO_UNAVAILABLE' then raise; end if; caught := true; end;
  if not caught then raise exception 'URL persisted'; end if;
  delete from storage.objects where bucket_id='listing-draft-media' and name=path;
  get diagnostics n = row_count; if n<>0 then raise exception 'associated object deleted'; end if;
  execute 'reset role'; perform set_config('request.jwt.claim.sub',outsider::text,true); execute 'set local role authenticated';
  if exists(select 1 from storage.objects where bucket_id='listing-draft-media') then raise exception 'outsider read'; end if;
  caught := false;
  begin insert into storage.objects(id,bucket_id,name,owner_id) values(gen_random_uuid(),'listing-draft-media',path,outsider::text);
  exception when insufficient_privilege then caught := true; end;
  if not caught then raise exception 'outsider uploaded'; end if;
  caught := false;
  begin perform public.set_listing_draft_photos(d.id,1,photos);
  exception when others then if sqlerrm<>'DRAFT_NOT_FOUND' then raise; end if; caught := true; end;
  if not caught then raise exception 'outsider associated'; end if;
  delete from storage.objects where bucket_id='listing-draft-media' and name=path;
  get diagnostics n=row_count; if n<>0 then raise exception 'outsider deleted'; end if;
  execute 'reset role'; perform set_config('request.jwt.claim.sub','',true); execute 'set local role anon';
  if exists(select 1 from storage.objects where bucket_id='listing-draft-media') then raise exception 'anonymous read'; end if;
  caught := false;
  begin perform public.set_listing_draft_photos(d.id,1,photos);
  exception when insufficient_privilege then caught:=true; end;
  if not caught then raise exception 'anonymous association'; end if;
  execute 'reset role'; perform set_config('request.jwt.claim.sub',actor::text,true); execute 'set local role authenticated';
  result := public.begin_listing_draft_publication(d.id,1,'{}');
  caught := false;
  begin perform public.set_listing_draft_photos(d.id,1,'[]');
  exception when others then if sqlerrm<>'PUBLICATION_IN_PROGRESS' then raise; end if; caught:=true; end;
  if not caught then raise exception 'frozen association changed'; end if;
  caught := false;
  begin insert into storage.objects(id,bucket_id,name,owner_id) values(gen_random_uuid(),'listing-draft-media',actor::text || '/' || d.id::text || '/50000000-0000-4000-8000-000000000003.jpg',actor::text);
  exception when insufficient_privilege then caught:=true; end;
  if not caught then raise exception 'frozen draft upload'; end if;
  -- Remove an unused upload only; source/public photos are never removed here.
  delete from storage.objects where bucket_id='listing-draft-media' and name=other_path;
  get diagnostics n=row_count; if n<>1 then raise exception 'unused object cleanup denied'; end if;
  select * into edit_d from public.listing_drafts where source_listing_id=listing and owner_id=actor and state='open';
  result := public.set_listing_draft_photos(edit_d.id,edit_d.revision,'[{"kind":"published","objectPath":"10000000-0000-4000-8000-000000000001/1.jpg"}]');
  result := public.set_listing_draft_photos(edit_d.id,result.revision,'[]');
  execute 'reset role';
  if not exists(select 1 from storage.objects where bucket_id='apartment-photos' and name=listing::text || '/1.jpg') then raise exception 'published source deleted'; end if;
  if not exists(select 1 from public.apartments a where a.id=listing and ('https://npbduvjnqnbydolmdpsc.supabase.co/storage/v1/object/public/apartment-photos/' || listing::text || '/1.jpg')=any(a.photos)) then raise exception 'published listing changed'; end if;
end $test$;
