do $test$
declare
  owner_id constant uuid := '00000000-0000-4000-8000-000000000001';
  outsider_id constant uuid := '00000000-0000-4000-8000-000000000002';
  published_key constant uuid := '10000000-0000-4000-8000-000000000001';
  receipt_draft constant uuid := '10000000-0000-4000-8000-000000000090';
  receipt constant uuid := '40000000-0000-4000-8000-000000000001';
  d public.listing_drafts;
  again public.listing_drafts;
  temp_draft public.listing_drafts;
  frozen public.listing_drafts;
  result public.listing_drafts;
  caught boolean;
begin
  perform set_config('request.jwt.claim.sub',owner_id::text,true);
  execute 'set local role authenticated';
  d := public.create_listing_draft(receipt,null,null,'{"title":"first"}');
  again := public.create_listing_draft(receipt,null,null,'{"title":"retry"}');
  if d.id <> again.id or again.fields <> '{"title":"first"}'::jsonb then raise exception 'import retry was not idempotent'; end if;
  temp_draft := public.create_listing_draft('40000000-0000-4000-8000-000000000002',published_key,0,'{}');
  again := public.create_listing_draft('40000000-0000-4000-8000-000000000002',published_key,0,'{}');
  if temp_draft.id <> again.id then raise exception 'edit import retry was not idempotent'; end if;
  result := public.save_listing_draft(d.id,0,'{"title":"saved"}');
  if result.revision <> 1 then raise exception 'revision did not advance'; end if;
  caught := false;
  begin perform public.save_listing_draft(d.id,0,'{"title":"stale"}');
  exception when others then if sqlerrm <> 'DRAFT_CONFLICT' then raise; end if; caught := true; end;
  if not caught or (select fields from public.listing_drafts where id=d.id) <> '{"title":"saved"}'::jsonb then raise exception 'stale save overwrote data'; end if;
  caught := false;
  begin perform public.complete_listing_draft(d.id,1);
  exception when others then if sqlerrm <> 'PUBLICATION_RECEIPT_REQUIRED' then raise; end if; caught := true; end;
  if not caught then raise exception 'completed without publication receipt'; end if;
  temp_draft := public.create_listing_draft();
  perform public.delete_listing_draft(temp_draft.id,0);
  if exists(select 1 from public.listing_drafts where id=temp_draft.id) then raise exception 'draft was not deleted'; end if;
  frozen := public.begin_listing_draft_publication(d.id,1,'{"title":"saved"}');
  again := public.begin_listing_draft_publication(d.id,1,'{"title":"saved"}');
  if frozen.publication_started_at is null or frozen.publication_started_at <> again.publication_started_at then raise exception 'begin is not retry safe'; end if;
  caught := false;
  begin perform public.begin_listing_draft_publication(d.id,1,'{"title":"changed"}');
  exception when others then if sqlerrm <> 'PUBLICATION_SNAPSHOT_CONFLICT' then raise; end if; caught := true; end;
  if not caught then raise exception 'changed publication payload was accepted'; end if;
  caught := false;
  begin perform public.delete_listing_draft(d.id,1);
  exception when others then if sqlerrm <> 'PUBLICATION_IN_PROGRESS' then raise; end if; caught := true; end;
  if not caught then raise exception 'deleted begun publication'; end if;
  caught := false;
  begin perform public.save_listing_draft(d.id,1,'{}');
  exception when others then if sqlerrm <> 'PUBLICATION_IN_PROGRESS' then raise; end if; caught := true; end;
  if not caught then raise exception 'changed frozen draft'; end if;
  result := public.cancel_listing_draft_publication(d.id,1);
  if result.publication_started_at is not null or result.publication_request_id = frozen.publication_request_id then raise exception 'cancel did not rotate and unlock'; end if;
  if not exists(select 1 from public.listing_draft_cancelled_attempts where request_key=frozen.publication_request_id) then raise exception 'cancelled key not retained'; end if;
  caught := false;
  begin perform public.begin_listing_draft_publication(d.id,1,'{"title":"saved"}');
  exception when others then if sqlerrm <> 'DRAFT_CONFLICT' then raise; end if; caught := true; end;
  if not caught then raise exception 'stale publication restarted after cancellation'; end if;
  result := public.save_listing_draft(d.id,2,'{"title":"resumed"}');
  if result.revision <> 3 then raise exception 'save after cancel failed'; end if;
  execute 'reset role';
  perform set_config('request.jwt.claim.sub',outsider_id::text,true);
  execute 'set local role authenticated';
  caught := false;
  begin perform public.save_listing_draft(d.id,1,'{}');
  exception when others then if sqlerrm <> 'DRAFT_NOT_FOUND' then raise; end if; caught := true; end;
  if not caught then raise exception 'outsider saved draft'; end if;
  execute 'reset role';
  -- The runner froze this draft and published the same payload through the actual RPC.
  update public.listing_drafts set publication_payload_hash=pg_catalog.sha256('different'::bytea) where id=receipt_draft;
  perform set_config('request.jwt.claim.sub',owner_id::text,true);
  execute 'set local role authenticated';
  caught := false;
  begin perform public.complete_listing_draft(receipt_draft,0);
  exception when others then if sqlerrm <> 'PUBLICATION_RECEIPT_REQUIRED' then raise; end if; caught := true; end;
  if not caught then raise exception 'mismatched receipt completed draft'; end if;
  execute 'reset role';
  update public.listing_drafts set publication_payload_hash=(select r.payload_hash from public.listing_publication_requests r where r.actor_id='00000000-0000-4000-8000-000000000001'::uuid and r.request_key=published_key) where id=receipt_draft;
  execute 'set local role authenticated';
  result := public.complete_listing_draft(receipt_draft,0);
  if result.state <> 'completed' then raise exception 'verified receipt did not complete'; end if;
  result := public.complete_listing_draft(receipt_draft,0);
  if result.state <> 'completed' then raise exception 'completion retry failed'; end if;
  execute 'reset role';
  perform set_config('request.jwt.claim.sub','',true);
  execute 'set local role anon';
  caught := false;
  begin perform public.create_listing_draft();
  exception when insufficient_privilege then caught := true; end;
  if not caught then raise exception 'anonymous created draft'; end if;
  execute 'reset role';
end
$test$;
